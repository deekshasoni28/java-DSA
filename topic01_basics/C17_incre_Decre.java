package topic01_basics;

public class C17_incre_Decre {
    public static void main(String[] args) {
        int x = 10 ;
       
        System.out.println(++x);

        int y = 6 ;
        
        System.out.println(y++);

        int c = 1;
        
        System.out.println(c--);

        int d = 10;
        
        System.out.println(--d);

    }
}
